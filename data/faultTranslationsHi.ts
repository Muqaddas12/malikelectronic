/**
 * Get translated fault data according to language.
 */
export function getTranslatedFault(
  inverterId: string,
  fault: InverterFaultDetail,
  language: string,
): InverterFaultDetail {
  if (!fault) {
    return fault;
  }

  if (language !== 'hi') {
    return fault;
  }

  const hiData = faultTranslationsHi[inverterId]?.[fault.id];
  if (!hiData) {
    return fault;
  }

  return {
    ...fault,
    title: hiData.title ?? fault.title,
    subtitle: hiData.subtitle ?? fault.subtitle,
    symptoms: hiData.symptoms ?? fault.symptoms,
    basicChecks: hiData.basicChecks ?? fault.basicChecks,
    technicalExplanation:
      hiData.technicalExplanation ?? fault.technicalExplanation,
    resistorValues: hiData.resistorValues ?? fault.resistorValues,
    possibleCauses: hiData.possibleCauses ?? fault.possibleCauses,
    repairProcedure: hiData.repairProcedure ?? fault.repairProcedure,
    circuitFlow: hiData.circuitFlow ?? fault.circuitFlow,
    importantNote: hiData.importantNote ?? fault.importantNote,
    diagnosis: hiData.diagnosis ?? fault.diagnosis,
  };
}

